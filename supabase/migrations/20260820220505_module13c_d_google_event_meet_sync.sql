-- Module 13C/D — Durable Google event synchronization and optional Google Meet.
-- Network calls never occur inside the ProFox booking transaction. Meeting changes enqueue after-commit work.

CREATE TABLE IF NOT EXISTS public.google_calendar_event_links (
  meeting_id uuid PRIMARY KEY REFERENCES public.sales_meetings(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
  calendar_id text NOT NULL DEFAULT 'primary',
  external_event_id text NOT NULL,
  conference_request_id text NOT NULL,
  meet_url text NOT NULL DEFAULT '',
  etag text NOT NULL DEFAULT '',
  conference_status text NOT NULL DEFAULT 'none' CHECK (conference_status IN ('none','pending','success','failed')),
  last_operation text NOT NULL DEFAULT 'upsert' CHECK (last_operation IN ('upsert','delete','reconcile')),
  last_synced_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(user_id,calendar_id,external_event_id)
);

CREATE TABLE IF NOT EXISTS public.google_calendar_sync_jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
  meeting_id uuid REFERENCES public.sales_meetings(id) ON DELETE CASCADE,
  job_type text NOT NULL CHECK (job_type IN ('refresh_busy','upsert_event','delete_event','reconcile_event')),
  dedupe_key text NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processing','retry','succeeded','reconnect_required','failed')),
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts>=0),
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  locked_at timestamptz,
  completed_at timestamptz,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_google_sync_jobs_due ON public.google_calendar_sync_jobs(status,next_attempt_at,id) WHERE status IN ('pending','retry','processing');
CREATE INDEX IF NOT EXISTS idx_google_sync_jobs_meeting ON public.google_calendar_sync_jobs(meeting_id,created_at DESC) WHERE meeting_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.google_calendar_sync_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES public.user_profiles(id) ON DELETE SET NULL,
  meeting_id uuid REFERENCES public.sales_meetings(id) ON DELETE SET NULL,
  job_id bigint REFERENCES public.google_calendar_sync_jobs(id) ON DELETE SET NULL,
  operation text NOT NULL,
  status text NOT NULL,
  http_status integer,
  detail text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_google_sync_audit_user_created ON public.google_calendar_sync_audit(user_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_google_sync_audit_meeting_created ON public.google_calendar_sync_audit(meeting_id,created_at DESC) WHERE meeting_id IS NOT NULL;

ALTER TABLE public.google_calendar_event_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.google_calendar_sync_jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.google_calendar_sync_audit ENABLE ROW LEVEL SECURITY;
