CREATE OR REPLACE FUNCTION public.is_public_reschedule_slot_available(p_salesperson_id uuid,p_start_at timestamptz,p_duration_minutes integer,p_ignore_meeting_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
  SELECT public.is_public_reschedule_slot_available_native_base(p_salesperson_id,p_start_at,p_duration_minutes,p_ignore_meeting_id)
     AND NOT public.has_google_calendar_conflict(p_salesperson_id,p_start_at,p_start_at+make_interval(mins=>p_duration_minutes),p_ignore_meeting_id);
$$;
REVOKE ALL ON FUNCTION public.is_public_reschedule_slot_available(uuid,timestamptz,integer,uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_public_reschedule_slot_available(uuid,timestamptz,integer,uuid) TO anon,authenticated,service_role;
